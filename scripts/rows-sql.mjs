#!/usr/bin/env node
// Turn reconciled flat catalog rows - spells, gear, skills, psionic powers,
// enchantments - into ONE data script.
//
//   node scripts/rows-sql.mjs <worker-json-dir> <out.sql> [--title "..."] [--notes <file>]
//   node scripts/rows-sql.mjs --self-test
//
// BOOK-INGEST-AUDIT F124, the shape scripts/bestiary-sql.mjs took under F112.
// The retrospective's gear and spell scripts (Warlords of Russia's price lists,
// Temporal Magic, the circles) came out of a generator in a session scratchpad;
// this is that generator, tracked. It covers ONLY the step from JSON to SQL:
// it refuses what it cannot write and repairs nothing. OPT-IN: no check
// requires it, no existing script is regenerated by it, and it refuses to
// overwrite a file that exists.
//
// INPUT. Every `*.json` in <worker-json-dir>, in filename order, is an object
// with any of these lists, each row's keys being that table's columns by name:
//
//   { "spells": [ ... ], "gear": [ ... ], "skills": [ ... ],
//     "psionic_powers": [ ... ], "enchantments": [ ... ] }
//
// A JSON-shaped column (a skill's `bonuses`) may be an object and is written
// as compact JSON.
//
// THE IDENTITY of a row is its table's portable key - `slug` for gear and
// enchantments, `name` for the rest (the triples in scripts/repo-vs-live.mjs).
// Catalog ids are insertion order and differ per environment, so nothing here
// reads or writes one.
//
// WHAT IT REFUSES, all of it reported in one pass, and nothing is written:
//   - a table this does not know, or a key that is not a column of its table
//     (read out of db/schema.sql);
//   - a missing NOT NULL value, a value outside a CHECK (... IN (...)) list, a
//     non-integer in an INTEGER column;
//   - an identity used twice, or a slug that is not kebab-case;
//   - a row with no source_book, since every catalog row cites its page;
//   - (a row with no `source` is NOT refused: it is written 'import'. The
//     schema's own default is 'seed', which means "shipped with the app", and
//     scripts/source-coverage.mjs counts a book's rows by `source = 'import'`.)
//   - a spell with a `tradition` whose name carries no "Prefix: " - the codex
//     splits a tradition into families by that prefix, and one bare name
//     collapses the split (BOOK-INGEST-AUDIT F123) - reported as a WARNING,
//     because a tradition may be all one family;
//   - any character outside printable ASCII, per value - fold it upstream.
//
// IT DOES NOT ASK WHETHER A ROW IS ALREADY IN THE CATALOG. That is
// `catalog-diff` and `class-check --remote`, before this runs. INSERT OR
// IGNORE leaves an existing row alone, and the read-backs count this script's
// own identities, so a held row passes them without being changed - which is
// right for a re-run and wrong for a correction. A correction is a `fix-`
// script written by hand.

import { writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadColumns, tableRow, kebabProblem, batchedInserts, countReadbacks, footer,
         readJsonDir, noteLines, outNameProblem, scriptProblem, titleProblem, parseArgs } from './sql-gen-lib.mjs';

// table -> the column that identifies a row across environments.
const IDENTITY = { spells: 'name', gear: 'slug', skills: 'name', psionic_powers: 'name', enchantments: 'slug' };
const TABLES = Object.keys(IDENTITY);

function buildRows(docs, columns) {
  const refusals = [];
  const warnings = [];
  const rows = Object.fromEntries(TABLES.map((t) => [t, []]));
  const seen = Object.fromEntries(TABLES.map((t) => [t, new Set()]));
  for (const { file, doc } of docs) {
    if (!doc || typeof doc !== 'object' || Array.isArray(doc)) { refusals.push(`${file}: not an object of table lists`); continue; }
    for (const [table, list] of Object.entries(doc)) {
      if (!TABLES.includes(table)) { refusals.push(`${file}: "${table}" is not a table this writes (${TABLES.join(', ')})`); continue; }
      if (!Array.isArray(list)) { refusals.push(`${file}: ${table} must be a list`); continue; }
      const key = IDENTITY[table];
      for (const input of list) {
        if (!input || typeof input !== 'object') { refusals.push(`${file}: a ${table} entry is not an object`); continue; }
        const where = `${file}: ${table} ${input[key] ?? `(no ${key})`}`;
        // A row a book brought in is an IMPORT. Left to the schema's default it
        // would be written 'seed', and source-coverage would stop counting it.
        const hasSource = columns[table].some((c) => c.name === 'source');
        const row = tableRow(table, columns[table],
          hasSource && input.source === undefined ? { ...input, source: 'import' } : input, where, refusals);
        if (key === 'slug') { const bad = kebabProblem(input.slug); if (bad) refusals.push(`${where}: ${bad}`); }
        const id = String(row[key] ?? '').toLowerCase();
        if (id && seen[table].has(id)) refusals.push(`${where}: this ${key} appears twice`);
        seen[table].add(id);
        if (columns[table].some((c) => c.name === 'source_book') && !row.source_book) {
          refusals.push(`${where}: source_book is required - every row cites its page`);
        }
        rows[table].push(row);
      }
    }
  }
  // One bare name in a tradition collapses the codex's split into families.
  const byTradition = new Map();
  for (const r of rows.spells) {
    if (!r.tradition) continue;
    if (!byTradition.has(r.tradition)) byTradition.set(r.tradition, []);
    byTradition.get(r.tradition).push(r.name);
  }
  for (const [t, names] of byTradition) {
    const bare = names.filter((n) => !String(n).includes(': '));
    if (bare.length && bare.length < names.length) {
      warnings.push(`spells: tradition "${t}" mixes prefixed names with ${bare.length} bare one(s) `
        + `(${bare.slice(0, 3).join(', ')}) - the codex then lists it unsplit`);
    }
  }
  if (!TABLES.some((t) => rows[t].length) && !refusals.length) refusals.push('no rows in the input');
  return { rows, refusals, warnings };
}

function renderScript({ title, fileName, columns, rows, sourceFiles, notes }) {
  const nonId = (t) => columns[t].filter((c) => !c.primary).map((c) => c.name);
  const used = TABLES.filter((t) => rows[t].length);
  const L = [];
  L.push(`-- ${title}`);
  L.push(`-- ${used.map((t) => `${rows[t].length} ${t} row${rows[t].length === 1 ? '' : 's'}`).join(', ')}.`);
  L.push('--');
  L.push('-- One-off data script, run once per environment. NOT a migration - it adds');
  L.push('-- rows, not schema.');
  L.push('--');
  L.push(`--   node scripts/d1-apply.mjs --local apps/character-creator/db/${fileName}`);
  L.push('--');
  L.push(`-- Written by scripts/rows-sql.mjs from ${sourceFiles} worker file(s). Every value is`);
  L.push('-- printable ASCII and every row cites its book. Rows are keyed on their');
  L.push('-- portable identity, never an id; a row already held is left as it is.');
  for (const n of notes) L.push(n);
  L.push('');
  for (const t of used) for (const s of batchedInserts(t, nonId(t), rows[t])) L.push(s, '');
  L.push('-- Read the result back. This script asserts its OWN rows and nothing else.');
  for (const t of used) {
    const key = IDENTITY[t];
    const hasBook = columns[t].some((c) => c.name === 'source_book');
    L.push(...countReadbacks(t, key, rows[t].map((r) => r[key]), `${t} rows`,
      hasBook ? ' AND source_book IS NOT NULL' : ''));
  }
  L.push('');
  L.push(...footer(fileName));
  return L.join('\n') + '\n';
}

function selfTest() {
  const columns = loadColumns(TABLES);
  const spell = { name: 'Test: First Light', level: 1, ppe: 2, tradition: 'test', system: 'rifts', source_book: 'Test Book p.1' };
  const gear = { slug: 'test-rope', name: 'Test Rope', system: 'rifts', category: 'gear', source_book: 'Test Book p.2' };
  const run = (doc) => buildRows([{ file: 't.json', doc }], columns);
  const cases = [
    ['clean rows in two tables are accepted', { spells: [spell], gear: [gear] },
      (r) => r.refusals.length === 0 && r.rows.spells.length === 1 && r.rows.gear.length === 1],
    ['a table it does not write is refused', { creatures: [] },
      (r) => r.refusals.some((x) => x.includes('"creatures" is not a table this writes'))],
    ['a key that is not a column is refused', { gear: [{ ...gear, colour: 'red' }] },
      (r) => r.refusals.some((x) => x.includes('"colour" is not a column of gear'))],
    ['an id is never written', { gear: [{ ...gear, id: 283 }] },
      (r) => r.refusals.some((x) => x.includes('row id and is never written'))],
    ['a gear slug that is not kebab-case is refused', { gear: [{ ...gear, slug: 'Test Rope' }] },
      (r) => r.refusals.some((x) => x.includes('not a kebab-case slug'))],
    ['an identity used twice is refused, whatever its case', { spells: [spell, { ...spell, name: 'test: first light' }] },
      (r) => r.refusals.some((x) => x.includes('this name appears twice'))],
    ['a row with no source_book is refused', { spells: [{ ...spell, source_book: undefined }] },
      (r) => r.refusals.some((x) => x.includes('source_book is required'))],
    ['a non-integer level is refused', { spells: [{ ...spell, level: 'one' }] },
      (r) => r.refusals.some((x) => x.includes('not an integer'))],
    ['a non-ASCII character is refused', { gear: [{ ...gear, name: 'Test — Rope' }] },
      (r) => r.refusals.some((x) => x.includes('outside printable ASCII'))],
    ['a tradition mixing prefixed and bare names is warned about, not refused',
      { spells: [spell, { ...spell, name: 'Bare Name' }] },
      (r) => r.refusals.length === 0 && r.warnings.some((x) => x.includes('lists it unsplit'))],
    ['an empty input is refused', {}, (r) => r.refusals.some((x) => x.includes('no rows in the input'))],
    ['a row that states no source is written as an import, never as the schema\'s seed default',
      { spells: [spell] }, (r) => r.rows.spells[0].source === 'import'],
    ['and a source the row does state is kept', { spells: [{ ...spell, source: 'seed' }] },
      (r) => r.rows.spells[0].source === 'seed'],
  ];
  let failed = 0;
  for (const [name, doc, ok] of cases) {
    const pass = ok(run(doc));
    if (!pass) failed++;
    console.log(`  ${pass ? 'ok  ' : 'FAIL'} ${name}`);
  }
  const many = { gear: Array.from({ length: 85 }, (_, i) => ({ ...gear, slug: `test-rope-${i}`, name: `Test Rope ${i}` })) };
  const r = run(many);
  const sql = renderScript({ title: 'Self-test.', fileName: '~999-self-test.sql', columns, rows: r.rows, sourceFiles: 1, notes: [] });
  const shape = [
    ['85 rows are batched into three inserts', (sql.match(/INSERT OR IGNORE INTO gear /g) || []).length === 3],
    ['and read back in three parts that sum to 85',
      (sql.match(/part \d: (\d+) are in/g) || []).map((s) => +s.match(/: (\d+)/)[1]).reduce((a, b) => a + b, 0) === 85],
    ['the script records its run', sql.trimEnd().endsWith("INSERT INTO data_script_runs (filename) VALUES ('~999-self-test.sql');")],
    ['in pure ASCII with no CR', scriptProblem(sql) === null],
    ['and writes no id column', !/\(id, /.test(sql)],
    // d1-apply sends every read-back as one command; past its budget the apply
    // lands and the assertions go unevaluated. Refused here instead.
    ['85 short rows fit the read-back budget', scriptProblem(sql) === null],
    ['and a script whose read-backs would not fit is refused', (() => {
      const big = { gear: Array.from({ length: 400 }, (_, i) => ({ ...gear,
        slug: `a-rather-long-slug-for-a-piece-of-gear-number-${i}`, name: `Gear ${i}` })) };
      const b = run(big);
      return /over d1-apply's 7900 budget/.test(scriptProblem(renderScript({ title: 't', fileName: '~999-self-test.sql',
        columns, rows: b.rows, sourceFiles: 1, notes: [] })) || '');
    })()],
  ];
  for (const [name, pass] of shape) { if (!pass) failed++; console.log(`  ${pass ? 'ok  ' : 'FAIL'} ${name}`); }
  console.log(failed ? `\nrows-sql self-test FAILED (${failed})` : '\nrows-sql self-test passed');
  process.exit(failed ? 1 : 0);
}

function main(argv) {
  const { flags, rest } = parseArgs(argv, ['--title', '--notes']);
  if (flags['--self-test']) return selfTest();
  const [dir, out] = rest;
  if (!dir || !out) {
    console.error('usage: node scripts/rows-sql.mjs <worker-json-dir> <out.sql> [--title "..."] [--notes <file>]\n'
      + '       node scripts/rows-sql.mjs --self-test');
    process.exit(2);
  }
  const fileName = path.basename(out);
  const nameBad = outNameProblem(fileName) || titleProblem(flags['--title']);
  if (nameBad) { console.error(`rows-sql: ${nameBad}`); process.exit(2); }
  if (existsSync(out)) { console.error(`rows-sql: ${out} exists - this never overwrites a data script`); process.exit(2); }
  const columns = loadColumns(TABLES);
  const docs = readJsonDir(dir);
  const built = buildRows(docs, columns);
  for (const w of built.warnings) console.error(`rows-sql: warning - ${w}`);
  if (built.refusals.length) {
    console.error(`rows-sql: ${built.refusals.length} refusal(s), nothing written:`);
    for (const r of built.refusals) console.error(`  - ${r}`);
    process.exit(1);
  }
  const sql = renderScript({ title: flags['--title'] || `Catalog rows from ${docs.length} worker file(s).`,
    fileName, columns, rows: built.rows, sourceFiles: docs.length, notes: noteLines(flags['--notes']) });
  const bad = scriptProblem(sql);
  if (bad) { console.error(`rows-sql: ${bad}; nothing written`); process.exit(1); }
  writeFileSync(out, sql);
  console.log(`rows-sql: wrote ${out} - ${TABLES.filter((t) => built.rows[t].length).map((t) => `${built.rows[t].length} ${t}`).join(', ')}. `
    + 'Check where it sorts, then apply it --local.');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main(process.argv.slice(2));
}
