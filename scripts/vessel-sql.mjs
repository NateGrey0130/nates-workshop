#!/usr/bin/env node
// Turn reconciled vehicle JSON into ONE data script: the `vehicles` rows, their
// `vehicle_locations` and their `vehicle_weapons`.
//
//   node scripts/vessel-sql.mjs <worker-json-dir> <out.sql> [--title "..."] [--notes <file>]
//   node scripts/vessel-sql.mjs --self-test
//
// BOOK-INGEST-AUDIT F124, the shape scripts/bestiary-sql.mjs took under F112.
// The Warlords of Russia, Triax 2 and retrospective vessel scripts each came
// out of a generator written in a session scratchpad; this is that generator,
// tracked. It covers ONLY the step from JSON to SQL. Extraction and
// reconciliation stay agent work: this refuses what it cannot write, it does
// not repair it. OPT-IN: no check requires it, no existing script is
// regenerated by it, and it refuses to overwrite a file that exists.
//
// INPUT. Every `*.json` in <worker-json-dir>, in filename order, is
//
//   { "vehicles": [ { "slug": ..., "name": ..., ...,
//                     "locations": [ { "location": ..., "mdc": ..., "mdc_note": ... } ],
//                     "weapons":   [ { "name": ..., "damage": ..., ... } ] } ] }
//
// A vehicle's keys are `vehicles` columns by name (no `id`). `locations` and
// `weapons` become child rows owned by its slug, in the order given: `ordinal`
// defaults to the entry's position, counted from 1, which is the book's own
// numbering for a weapon and the printed order for a location.
//
// WHAT IT REFUSES, all of it reported in one pass, and nothing is written:
//   - a key that is not a column (read out of db/schema.sql);
//   - a missing NOT NULL value, a value outside a CHECK (... IN (...)) list, a
//     non-integer in an INTEGER column, a slug that is not kebab-case or is
//     used twice, a location or an ordinal used twice on one vehicle;
//   - a "Main Body" location whose M.D.C. disagrees with the vehicle's own
//     mdc_main_body - the two are the same printed figure;
//   - a row with no source_book, since every catalog row cites its page;
//   - any character outside printable ASCII, per value - fold it upstream.
//
// OUTPUT. INSERT OR IGNORE in batches, then read-backs that assert this
// script's OWN rows by slug, then the `data_script_runs` line.

import { writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadColumns, tableRow, kebabProblem, batchedInserts, inList, countReadbacks, footer,
         readJsonDir, noteLines, outNameProblem, scriptProblem, titleProblem, parseArgs, sqlLiteral } from './sql-gen-lib.mjs';

const TABLES = ['vehicles', 'vehicle_locations', 'vehicle_weapons'];
const MAIN_BODY = 'Main Body';

function buildRows(docs, columns) {
  const refusals = [];
  const vehicles = [];
  const locations = [];
  const weapons = [];
  const slugs = new Set();
  for (const { file, doc } of docs) {
    const list = doc?.vehicles;
    if (!Array.isArray(list)) { refusals.push(`${file}: no "vehicles" list`); continue; }
    for (const v of list) {
      const where = `${file}: ${v?.slug ?? '(no slug)'}`;
      if (!v || typeof v !== 'object') { refusals.push(`${file}: a vehicle entry is not an object`); continue; }
      const row = tableRow('vehicles', columns.vehicles, v, where, refusals, ['locations', 'weapons']);
      const slugBad = kebabProblem(v.slug);
      if (slugBad) refusals.push(`${where}: ${slugBad}`);
      if (slugs.has(v.slug)) refusals.push(`${where}: this slug appears twice`);
      slugs.add(v.slug);
      if (!row.source_book) refusals.push(`${where}: source_book is required - every row cites its page`);
      vehicles.push(row);

      const seenLoc = new Set();
      (Array.isArray(v.locations) ? v.locations : []).forEach((l, i) => {
        const lw = `${where} location ${i + 1}`;
        const r = tableRow('vehicle_locations', columns.vehicle_locations,
          { ordinal: i + 1, ...l, vehicle_slug: v.slug }, lw, refusals);
        if (seenLoc.has(r.location)) refusals.push(`${lw}: "${r.location}" appears twice on this vehicle`);
        seenLoc.add(r.location);
        if (r.location === MAIN_BODY && Number.isInteger(r.mdc) && Number.isInteger(row.mdc_main_body)
            && r.mdc !== row.mdc_main_body) {
          refusals.push(`${lw}: Main Body is ${r.mdc} M.D.C. and the vehicle's mdc_main_body is ${row.mdc_main_body}`);
        }
        locations.push(r);
      });
      if (v.locations !== undefined && !Array.isArray(v.locations)) refusals.push(`${where}: locations must be a list`);

      const seenOrd = new Set();
      (Array.isArray(v.weapons) ? v.weapons : []).forEach((w, i) => {
        const ww = `${where} weapon ${i + 1}`;
        const r = tableRow('vehicle_weapons', columns.vehicle_weapons,
          { ordinal: i + 1, ...w, vehicle_slug: v.slug }, ww, refusals);
        if (seenOrd.has(r.ordinal)) refusals.push(`${ww}: ordinal ${r.ordinal} appears twice on this vehicle`);
        seenOrd.add(r.ordinal);
        weapons.push(r);
      });
      if (v.weapons !== undefined && !Array.isArray(v.weapons)) refusals.push(`${where}: weapons must be a list`);
    }
  }
  if (!vehicles.length && !refusals.length) refusals.push('no vehicle rows in the input');
  return { vehicles, locations, weapons, refusals };
}

function renderScript({ title, fileName, columns, vehicles, locations, weapons, sourceFiles, notes }) {
  const nonId = (t) => columns[t].filter((c) => !c.primary).map((c) => c.name);
  const slugs = vehicles.map((r) => r.slug);
  const L = [];
  L.push(`-- ${title}`);
  L.push(`-- ${vehicles.length} vehicle rows, with ${locations.length} locations and ${weapons.length} weapon entries.`);
  L.push('--');
  L.push('-- One-off data script, run once per environment. NOT a migration - it adds');
  L.push('-- rows, not schema.');
  L.push('--');
  L.push(`--   node scripts/d1-apply.mjs --local apps/character-creator/db/${fileName}`);
  L.push('--');
  L.push(`-- Written by scripts/vessel-sql.mjs from ${sourceFiles} worker file(s). Every value`);
  L.push('-- is printable ASCII, every row cites its book, and a Main Body location');
  L.push('-- agrees with its vehicle\'s mdc_main_body.');
  for (const n of notes) L.push(n);
  L.push('');
  for (const s of [
    ...batchedInserts('vehicles', nonId('vehicles'), vehicles),
    ...batchedInserts('vehicle_locations', nonId('vehicle_locations'), locations),
    ...batchedInserts('vehicle_weapons', nonId('vehicle_weapons'), weapons),
  ]) L.push(s, '');
  L.push('-- Read the result back. This script asserts its OWN rows and nothing else.');
  L.push(...countReadbacks('vehicles', 'slug', slugs, 'machines'));
  L.push(`SELECT ${sqlLiteral(`their ${locations.length} locations are in`)} AS assertion, count(*) AS got, ${locations.length} AS want`);
  L.push(`  FROM vehicle_locations WHERE vehicle_slug IN ${inList(slugs)};`);
  L.push(`SELECT ${sqlLiteral(`their ${weapons.length} weapon entries are in`)} AS assertion, count(*) AS got, ${weapons.length} AS want`);
  L.push(`  FROM vehicle_weapons WHERE vehicle_slug IN ${inList(slugs)};`);
  L.push("SELECT 'each main body location equals mdc_main_body' AS assertion, count(*) AS got, 0 AS want");
  L.push(`  FROM vehicles v JOIN vehicle_locations l ON l.vehicle_slug = v.slug AND l.location = ${sqlLiteral(MAIN_BODY)}`);
  L.push(`  WHERE v.slug IN ${inList(slugs)} AND l.mdc IS NOT NULL AND v.mdc_main_body IS NOT NULL AND l.mdc <> v.mdc_main_body;`);
  L.push('');
  L.push(...footer(fileName));
  return L.join('\n') + '\n';
}

function selfTest() {
  const columns = loadColumns(TABLES);
  const good = { slug: 'test-walker', name: 'Test Walker', system: 'rifts', vehicle_class: 'robot',
    mdc_main_body: 300, is_mega_damage: 1, source_book: 'Test Book p.1',
    locations: [{ location: 'Main Body', mdc: 300 }, { location: 'Legs (2)', mdc: 100, mdc_note: 'Each.' }],
    weapons: [{ name: 'Rail Gun', damage: '1D4x10 M.D.', is_mega_damage: 1 }] };
  const run = (v) => buildRows([{ file: 't.json', doc: { vehicles: v } }], columns);
  const cases = [
    ['a clean vehicle is accepted, children ordered from 1', [good],
      (r) => r.refusals.length === 0 && r.locations[1].ordinal === 2 && r.weapons[0].ordinal === 1
        && r.locations[0].vehicle_slug === 'test-walker'],
    ['a key that is not a column is refused', [{ ...good, colour: 'red' }],
      (r) => r.refusals.some((x) => x.includes('"colour" is not a column of vehicles'))],
    ['a child key that is not a column is refused', [{ ...good, weapons: [{ name: 'X', calibre: 9 }] }],
      (r) => r.refusals.some((x) => x.includes('"calibre" is not a column of vehicle_weapons'))],
    ['a slug that is not kebab-case is refused', [{ ...good, slug: 'Test Walker' }],
      (r) => r.refusals.some((x) => x.includes('not a kebab-case slug'))],
    ['a slug used twice is refused', [good, good],
      (r) => r.refusals.some((x) => x.includes('appears twice'))],
    ['a value outside the system CHECK is refused', [{ ...good, system: 'traveller' }],
      (r) => r.refusals.some((x) => x.includes('is not one of'))],
    ['a missing name is refused', [{ ...good, name: undefined }],
      (r) => r.refusals.some((x) => x.includes('name is required'))],
    ['a Main Body that disagrees with mdc_main_body is refused',
      [{ ...good, locations: [{ location: 'Main Body', mdc: 250 }] }],
      (r) => r.refusals.some((x) => x.includes('Main Body is 250'))],
    ['a row with no source_book is refused', [{ ...good, source_book: undefined }],
      (r) => r.refusals.some((x) => x.includes('source_book is required'))],
    ['a non-ASCII character is refused', [{ ...good, name: 'Test — Walker' }],
      (r) => r.refusals.some((x) => x.includes('outside printable ASCII'))],
    ['a location named twice on one vehicle is refused',
      [{ ...good, locations: [{ location: 'Arm', mdc: 1 }, { location: 'Arm', mdc: 2 }] }],
      (r) => r.refusals.some((x) => x.includes('"Arm" appears twice'))],
  ];
  let failed = 0;
  for (const [name, input, ok] of cases) {
    const pass = ok(run(input));
    if (!pass) failed++;
    console.log(`  ${pass ? 'ok  ' : 'FAIL'} ${name}`);
  }
  const r = run([good]);
  const sql = renderScript({ title: 'Self-test.', fileName: '~999-self-test.sql', columns, ...r, sourceFiles: 1, notes: [] });
  const shape = [
    ['the script inserts all three tables', /INSERT OR IGNORE INTO vehicles /.test(sql)
      && /INSERT OR IGNORE INTO vehicle_locations /.test(sql) && /INSERT OR IGNORE INTO vehicle_weapons /.test(sql)],
    ['reads its own rows back by slug', sql.includes("FROM vehicles WHERE slug IN ('test-walker')")],
    ['and records its run', sql.trimEnd().endsWith("INSERT INTO data_script_runs (filename) VALUES ('~999-self-test.sql');")],
    ['in pure ASCII with no CR', scriptProblem(sql) === null],
  ];
  for (const [name, pass] of shape) { if (!pass) failed++; console.log(`  ${pass ? 'ok  ' : 'FAIL'} ${name}`); }
  console.log(failed ? `\nvessel-sql self-test FAILED (${failed})` : '\nvessel-sql self-test passed');
  process.exit(failed ? 1 : 0);
}

function main(argv) {
  const { flags, rest } = parseArgs(argv, ['--title', '--notes']);
  if (flags['--self-test']) return selfTest();
  const [dir, out] = rest;
  if (!dir || !out) {
    console.error('usage: node scripts/vessel-sql.mjs <worker-json-dir> <out.sql> [--title "..."] [--notes <file>]\n'
      + '       node scripts/vessel-sql.mjs --self-test');
    process.exit(2);
  }
  const fileName = path.basename(out);
  const nameBad = outNameProblem(fileName) || titleProblem(flags['--title']);
  if (nameBad) { console.error(`vessel-sql: ${nameBad}`); process.exit(2); }
  if (existsSync(out)) { console.error(`vessel-sql: ${out} exists - this never overwrites a data script`); process.exit(2); }
  const columns = loadColumns(TABLES);
  const docs = readJsonDir(dir);
  const built = buildRows(docs, columns);
  if (built.refusals.length) {
    console.error(`vessel-sql: ${built.refusals.length} refusal(s), nothing written:`);
    for (const r of built.refusals) console.error(`  - ${r}`);
    process.exit(1);
  }
  const sql = renderScript({ title: flags['--title'] || `Vehicles from ${docs.length} worker file(s).`,
    fileName, columns, ...built, sourceFiles: docs.length, notes: noteLines(flags['--notes']) });
  const bad = scriptProblem(sql);
  if (bad) { console.error(`vessel-sql: ${bad}; nothing written`); process.exit(1); }
  writeFileSync(out, sql);
  console.log(`vessel-sql: wrote ${out} - ${built.vehicles.length} vehicles, ${built.locations.length} locations, `
    + `${built.weapons.length} weapons. Check where it sorts, then apply it --local.`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main(process.argv.slice(2));
}
