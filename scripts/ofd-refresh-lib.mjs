// The pure half of ofd-refresh.mjs, so the FilamentForge smoke test can run
// it — the same split class-check.mjs / class-check-lib.mjs uses. Everything
// here is deterministic: CSV text in, SQL text out. The fetching, the target
// flag and the wrangler call stay in the CLI.

export const MIN_BRANDS = 10;      // below these, assume OFD is broken and keep
export const MIN_FILAMENTS = 100;  // the snapshot we already have
export const ROWS_PER_INSERT = 100;

export const FILAMENT_COLUMNS = [
  'id', 'brand_id', 'name', 'material', 'density', 'diameter_tolerance',
  'min_print_temperature', 'max_print_temperature', 'min_bed_temperature',
  'max_bed_temperature', 'max_dry_temperature', 'slicer_settings',
];

// The parser the app used when it fetched OFD itself.
export function parseCSVLine(line) {
  const result = [];
  let current = '';
  let inQuotes = false;
  for (let i = 0; i < line.length; i++) {
    const c = line[i];
    if (c === '"') {
      if (inQuotes && i + 1 < line.length && line[i + 1] === '"') {
        current += '"';
        i++;
      } else {
        inQuotes = !inQuotes;
      }
    } else if (c === ',' && !inQuotes) {
      result.push(current);
      current = '';
    } else {
      current += c;
    }
  }
  result.push(current);
  return result;
}

export function parseCSV(text) {
  const lines = text.replace(/\r/g, '').split('\n').filter((l) => l.trim());
  if (lines.length < 2) return [];
  const headers = parseCSVLine(lines[0]);
  const results = [];
  for (let i = 1; i < lines.length; i++) {
    const vals = parseCSVLine(lines[i]);
    if (vals.length < headers.length - 2) continue; // skip garbage lines
    const obj = {};
    headers.forEach((h, idx) => { obj[h] = vals[idx] || ''; });
    results.push(obj);
  }
  return results;
}

// Dedupe by id: the tables key on it, and a duplicate CSV line must not fail
// the whole apply. Later rows win, which is arbitrary but stated.
export function dedupeById(rows) {
  return [...new Map(rows.filter((r) => r.id).map((r) => [r.id, r])).values()];
}

// A SQL string literal that is pure ASCII whatever the value holds: quotes
// doubled, control characters dropped, and every non-ASCII character spliced
// in as char(N) — non-ASCII through wrangler on Windows has produced mojibake
// in production (see d1-apply.mjs).
export function sqlLit(value) {
  const s = String(value ?? '');
  let out = "'";
  for (const ch of s) {
    const code = ch.codePointAt(0);
    if (code < 32) continue;               // control chars have no business in a name
    if (ch === "'") out += "''";
    else if (code > 126) out += "'||char(" + code + ")||'";
    else out += ch;
  }
  return out + "'";
}

export function insertChunks(table, columns, rows) {
  const statements = [];
  for (let i = 0; i < rows.length; i += ROWS_PER_INSERT) {
    const chunk = rows.slice(i, i + ROWS_PER_INSERT);
    const values = chunk.map((r) => '(' + columns.map((c) => sqlLit(r[c])).join(', ') + ')');
    statements.push(`INSERT INTO ${table} (${columns.join(', ')}) VALUES\n${values.join(',\n')};`);
  }
  return statements;
}

// The whole generated artifact. DELETE both tables, then rebuild — filaments
// before brands on the way down so no moment holds a filament whose brand row
// is already gone.
export function buildSnapshotSql(brands, filaments, fetchedAt) {
  for (const b of brands) b.fetched_at = fetchedAt;
  for (const f of filaments) f.fetched_at = fetchedAt;
  return [
    '-- Generated by scripts/ofd-refresh.mjs - do not commit.',
    'DELETE FROM ff_filaments;',
    'DELETE FROM ff_brands;',
    ...insertChunks('ff_brands', ['id', 'name', 'fetched_at'], brands),
    ...insertChunks('ff_filaments', [...FILAMENT_COLUMNS, 'fetched_at'], filaments),
  ].join('\n') + '\n';
}
