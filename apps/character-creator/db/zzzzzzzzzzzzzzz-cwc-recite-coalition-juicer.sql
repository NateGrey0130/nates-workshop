## Lore

The Coalition States have long campaigned against the Juicer process, calling
it a stupid, dangerous way to trade a healthy life for an early grave, and for
decades creating a Juicer inside the CS was punishable by death. Yet the
military sat on pre-Rifts Juicer technology for nearly a century while analysts
argued for it: stronger, faster, tireless soldiers whose front-line casualties
might fall from 80% to 20-30%, and at a quarter of the price of a basic suit of
power armor.

Emperor Prosek long refused. His son Joseph proposed using would-be citizens
from the ''Burbs and wastelands instead, and a three-year study of 400 Juicers
under Colonel Lyboc and General Cabot backed the idea. After the Juicer
Uprising the Emperor gave way: Juicer technology is now legal under the
military''s exclusive control, limited to two Army Divisions under Cabot, and
the Psycho-Juicer remains forbidden.

A human volunteer earns citizenship for himself and two family members with a
two-year tour, after which he undergoes detox. Some sign on again; a few serve
the full six years. A five-year tour from the start brings citizenship for five
family members, and many desperate people take it knowing it is a death
sentence. Most stay loyal for their families'' sake.

## GM Notes

**Where the numbers are.** Two Army Divisions is 11,520 troops. Lyboc still
runs a private force of 50 Juicers and 50 Psycho-Juicers in the Chi-Town
''Burbs, and can make more of the outlawed kind.

**Free Quebec.** The same pages describe Quebec''s secret Liberty Reserve at Old
Bones, now the Liberty Army Corps under General LeNoir, with around 10,000
Juicers reinstated and up to 15,000 augmented troops expected, far more than
Chi-Town''s intelligence believes.

**Demographics.** Juicer Uprising (p.30) puts Coalition Juicers at 2% of all
Juicers in North America, and rising. Coalition War Campaign gives no figure.

**This is the only Juicer with cybernetics, and the only one who cannot quit.**
The bomb in his skull goes off if he deserts. Whether the player knows about it
is a decision worth making before the campaign starts.
