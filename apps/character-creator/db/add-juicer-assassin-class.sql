## Lore

Not all Juicers are front-line warriors who charge in trusting to enhanced
strength and reflexes. A few specialise in the subtler end of the work -
espionage, and assassination. The "Juicer Assassin" series of rifles was named
for exactly this kind of enhanced killer.

Most of them train extensively *before* taking the conversion, which is what
makes this a different character from a Juicer who later learned to be quiet.
And a growing number treat the whole arc as a business plan: train as an
assassin, become a Juicer, earn millions over two years, then detox out and
retire rich.

About 45% of them become addicted instead, and spend what is left of their lives
as chemically enhanced spies and killers. Enough people do make it out to keep
the others trying.

Juicer Assassins are experts at moving silently, at camouflage, at evasion and
guerrilla tactics. They are as likely to kill with one precise shot or a stab in
the dark as to come through the front door shooting, and they tend to be colder
and less impulsive than their gung-ho brethren. Many model themselves on
mythological figures like James Bond or Julian Amici - expensive clothes, refined
manner, everything calculated.

## GM Notes

**Nothing is closed to this class.** Every skill category is open, several at
+10%, and the schedule runs to level fifteen. He is the most broadly capable
character in the book, and pays for it by being an ordinary Juicer underneath.

**The two-year business plan is a campaign structure.** A Juicer Assassin who
has a detox date is a character with a countdown and a reason to take the jobs
nobody else will. A Juicer Assassin who has passed it is a character who failed
at the one thing he planned.

**He starts at Hand to Hand: Assassin**, which means an evil alignment by the
usual reading - worth settling with the player before the first session rather
than after it.
