## Lore

Peacekeepers are the uniformed street police of the Coalition''s cities: beat
cops in old style Dead Boy armor or SAMAS power armor who break up fights,
direct traffic, watch for criminals and monsters and answer emergencies on sky
cycles. Their visibility is the point - a daily show of strength that keeps the
peace and reassures citizens. Crimes that need long investigation go to the
Inspectors, much as pre-Rifts detectives took over from uniformed officers.

## GM Notes

The ISS is police, not military: the Army enters a city only when invited by the
Emperor, the regional ISS head, the Governor or the High-Mayor, and the latter
three only in an emergency. ISS officers may search, wiretap, enter homes
secretly and hold suspects for 72 hours on suspicion alone. They treat ordinary
citizens with restraint and are widely seen as heroes, but practitioners of
magic, unregistered psychics, cyborgs, Crazies and Juicers are always treated as
armed and dangerous, and nonhumans and the supernatural are met with lethal
force. The ISS polices its own harshly; traitors in the ranks may simply
disappear. Armor often carries CPD or ISS lettering.
