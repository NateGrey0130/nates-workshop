## Lore

Specters - formally ISS Inspectors - are the Coalition''s police detectives.
They work crime scenes, question witnesses and gather evidence, in full armor,
uniform or plain clothes, and they are the officers who go undercover against
body-chop-shops, cyber-snatchers, subversives, smugglers, kidnappers and
murderers. They watch constantly for signs of magic or the supernatural.

## GM Notes

A case touching magic, psionics or the supernatural usually brings in an NTSET
operative or a Psi-Net Inspector; all three fall under the ISS umbrella and
share information freely. The street calls ISS officers "specters," and they
cultivate the image of shadowy figures who appear from nowhere to deal out
justice; they are rewarded for creative methods and are not restricted in how
