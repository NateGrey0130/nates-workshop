## Lore

Psi-Net is the Coalition''s civilian psychic authority. It runs the Psychic
Registration Program and bar-code identification, re-examines every registered
psychic every five years, catches psionic criminals, runs the psychic prison
wing and recruits psychics for the military and the ISS.

Its agents are psychic police. They monitor registrants, enforce the PRP laws,
scan visitors at the city gates for psychics, shapechangers, mages and the
supernatural, and join ISS and NTSET investigations, above all those involving
mind control.

## GM Notes

The public largely trusts Psi-Net, but the most extreme human supremacists
distrust any psychic and object to psychics policing their own kind. A
psychic who registers and serves is offered prestige and a good life; one who
refuses a conformity program is watched, and one judged beyond reform may be
executed without trial. Psi-Battalion, the Army''s psychic special forces
under Lt. Colonel Carol Black, is a separate branch.
